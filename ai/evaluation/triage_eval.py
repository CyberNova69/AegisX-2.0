"""
AegisX Triage Evaluation Framework
===================================

Computes evaluation metrics (accuracy, macro F1, confusion matrix, confidence statistics,
severity accuracy, investigation agreement, and grounding) for TriageAgent predictions
against ground-truth dataset records.
"""

from collections import Counter, defaultdict
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Set

from ai.agents.schemas import (
    VALID_CLASSIFICATIONS,
    VALID_SEVERITIES,
    TriageResult,
)
from ai.evaluation.metrics import (
    compute_accuracy,
    compute_confusion_matrix,
    compute_per_class_metrics,
    compute_macro_metrics,
    compute_evidence_grounding_stats,
)

@dataclass
class TriageEvalMetrics:
    """Consolidated evaluation metrics for TriageAgent performance."""
    total_examples: int = 0
    correct_classifications: int = 0
    accuracy: float = 0.0
    macro_precision: float = 0.0
    macro_recall: float = 0.0
    macro_f1: float = 0.0
    per_class_metrics: Dict[str, Dict[str, float]] = field(default_factory=dict)
    confusion_matrix: Dict[str, Dict[str, int]] = field(default_factory=lambda: defaultdict(Counter))
    classification_counts: Dict[str, int] = field(default_factory=Counter)
    
    # Severity & Investigation Decision
    correct_severities: int = 0
    severity_accuracy: float = 0.0
    investigation_agreement_count: int = 0
    investigation_agreement_pct: float = 0.0
    
    # Confidence & Structural Validity
    avg_confidence: float = 0.0
    structured_output_valid_count: int = 0
    structured_output_validity_rate: float = 0.0
    
    # Evidence Grounding
    evidence_grounding_rate: float = 1.0
    hallucinated_evidence_rate: float = 0.0
    total_hallucinations: int = 0

    def to_dict(self) -> Dict[str, Any]:
        return {
            "total_examples": self.total_examples,
            "correct_classifications": self.correct_classifications,
            "accuracy": round(self.accuracy, 4),
            "macro_precision": round(self.macro_precision, 4),
            "macro_recall": round(self.macro_recall, 4),
            "macro_f1": round(self.macro_f1, 4),
            "per_class_metrics": self.per_class_metrics,
            "confusion_matrix": {k: dict(v) for k, v in self.confusion_matrix.items()},
            "classification_counts": dict(self.classification_counts),
            "correct_severities": self.correct_severities,
            "severity_accuracy": round(self.severity_accuracy, 4),
            "investigation_agreement_count": self.investigation_agreement_count,
            "investigation_agreement_pct": round(self.investigation_agreement_pct, 4),
            "avg_confidence": round(self.avg_confidence, 4),
            "structured_output_validity_rate": round(self.structured_output_validity_rate, 4),
            "evidence_grounding_rate": round(self.evidence_grounding_rate, 4),
            "hallucinated_evidence_rate": round(self.hallucinated_evidence_rate, 4),
            "total_hallucinations": self.total_hallucinations,
        }

def evaluate_triage_predictions(
    predictions: List[TriageResult],
    ground_truth_records: List[Dict[str, Any]],
) -> TriageEvalMetrics:
    """
    Compare TriageAgent predictions against ground-truth dataset records.
    
    Args:
        predictions: List of TriageResult objects generated by TriageAgent.
        ground_truth_records: List of original dataset record dictionaries.
        
    Returns:
        TriageEvalMetrics: Comprehensive evaluated metrics.
    """
    if len(predictions) != len(ground_truth_records):
        raise ValueError(
            f"Mismatch in count: {len(predictions)} predictions vs {len(ground_truth_records)} ground-truth records."
        )

    metrics = TriageEvalMetrics(total_examples=len(predictions))
    if not predictions:
        return metrics

    pred_classes: List[str] = []
    gt_classes: List[str] = []
    pred_severities: List[str] = []
    gt_severities: List[str] = []
    total_conf = 0.0

    total_findings_evaluated = 0
    grounded_findings_count = 0
    total_hallucinations = 0

    for pred, gt in zip(predictions, ground_truth_records):
        gt_out = gt.get("output", {})
        gt_cls = gt_out.get("classification", "unknown")
        gt_sev = gt.get("input", {}).get("alert", {}).get("severity", "unknown")

        pred_cls = getattr(pred, "classification", "unknown")
        pred_sev = getattr(pred, "severity", "unknown")
        pred_conf = getattr(pred, "confidence", 0.5)

        pred_classes.append(pred_cls)
        gt_classes.append(gt_cls)
        pred_severities.append(pred_sev)
        gt_severities.append(gt_sev)

        metrics.classification_counts[pred_cls] += 1
        total_conf += pred_conf

        if pred_cls == gt_cls:
            metrics.correct_classifications += 1
        if pred_sev == gt_sev:
            metrics.correct_severities += 1

        # Investigation required agreement (non-benign requires investigation)
        expected_inv = (gt_cls != "benign")
        pred_inv = getattr(pred, "investigation_required", False)
        if pred_inv == expected_inv:
            metrics.investigation_agreement_count += 1

        # Structured output validity
        if pred_cls in VALID_CLASSIFICATIONS and pred_sev in VALID_SEVERITIES:
            metrics.structured_output_valid_count += 1

        # Grounding check on findings
        valid_ids: Set[str] = {
            e.get("id") for e in gt.get("input", {}).get("evidence", []) if "id" in e
        }
        findings = getattr(pred, "findings", [])
        for f in findings:
            total_findings_evaluated += 1
            f_eids = getattr(f, "evidence_ids", []) if hasattr(f, "evidence_ids") else f.get("evidence_ids", [])
            if f_eids:
                if all(eid in valid_ids for eid in f_eids):
                    grounded_findings_count += 1
                else:
                    for eid in f_eids:
                        if eid not in valid_ids:
                            total_hallucinations += 1

    n = metrics.total_examples
    metrics.accuracy = metrics.correct_classifications / n if n > 0 else 0.0
    metrics.severity_accuracy = metrics.correct_severities / n if n > 0 else 0.0
    metrics.investigation_agreement_pct = metrics.investigation_agreement_count / n if n > 0 else 0.0
    metrics.avg_confidence = total_conf / n if n > 0 else 0.0
    metrics.structured_output_validity_rate = metrics.structured_output_valid_count / n if n > 0 else 0.0

    # Macro and Per-Class Metrics
    labels = sorted(list(VALID_CLASSIFICATIONS))
    metrics.confusion_matrix = compute_confusion_matrix(pred_classes, gt_classes, labels=labels)
    metrics.per_class_metrics = compute_per_class_metrics(pred_classes, gt_classes, labels=labels)
    macro = compute_macro_metrics(metrics.per_class_metrics)
    metrics.macro_precision = macro["macro_precision"]
    metrics.macro_recall = macro["macro_recall"]
    metrics.macro_f1 = macro["macro_f1"]

    # Grounding ratios
    metrics.total_hallucinations = total_hallucinations
    if total_findings_evaluated > 0:
        metrics.evidence_grounding_rate = grounded_findings_count / total_findings_evaluated
        metrics.hallucinated_evidence_rate = total_hallucinations / total_findings_evaluated
    else:
        metrics.evidence_grounding_rate = 1.0
        metrics.hallucinated_evidence_rate = 0.0

    return metrics
